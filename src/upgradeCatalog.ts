export class UpgradeManager {
  currentLevels: Map<UpgradeCategory, number> = new Map();

  constructor(initialLevels?: Partial<Record<UpgradeCategory, number>>) {
    // Default all categories to level 1
    const categories: UpgradeCategory[] = [
      'table',
      'seat',
      'tea_equipment',
      'cooking_equipment',
      'display_cabinet',
      'hotel_room',
      'refrigeration',
      'lighting_power',
      'water_supply',
    ];
    for (const c of categories) {
      this.currentLevels.set(c, initialLevels?.[c] ?? 1);
    }
  }

  getLevel(category: UpgradeCategory): number {
    return this.currentLevels.get(category) ?? 1;
  }

  getCurrentTier(category: UpgradeCategory): UpgradeTierDef {
    const lvl = this.getLevel(category);
    const list = UPGRADE_CATALOG[category];
    return list[lvl - 1] ?? list[0];
  }

  getNextTier(category: UpgradeCategory): UpgradeTierDef | null {
    const lvl = this.getLevel(category);
    const list = UPGRADE_CATALOG[category];
    if (lvl >= list.length) return null;
    return list[lvl];
  }

  canUpgrade(
    category: UpgradeCategory,
    stage: number,
    money: number,
    rep: number,
    availableMaterials: Record<string, number>,
  ): { ok: boolean; reason?: string } {
    const next = this.getNextTier(category);
    if (!next) return { ok: false, reason: 'Already at maximum level.' };
    if (stage < next.stageRequired) return { ok: false, reason: `Requires Stage ${next.stageRequired}.` };
    if (rep < next.reputationRequired) return { ok: false, reason: `Requires Reputation ${next.reputationRequired.toFixed(1)}.` };
    if (money < next.cost) return { ok: false, reason: `Need ₹${next.cost.toLocaleString()} (Have ₹${Math.floor(money).toLocaleString()}).` };

    for (const [mat, reqQty] of Object.entries(next.materials)) {
      const have = availableMaterials[mat] ?? 0;
      if (have < reqQty) return { ok: false, reason: `Missing ${reqQty - have} ${mat}.` };
    }

    return { ok: true };
  }

  applyUpgrade(category: UpgradeCategory): boolean {
    const next = this.getNextTier(category);
    if (!next) return false;
    this.currentLevels.set(category, next.level);
    return true;
  }

  exportState(): Record<UpgradeCategory, number> {
    const obj = {} as Record<UpgradeCategory, number>;
    for (const [k, v] of this.currentLevels) {
      obj[k] = v;
    }
    return obj;
  }

  importState(data?: Partial<Record<UpgradeCategory, number>>) {
    if (!data) return;
    for (const [k, v] of Object.entries(data)) {
      if (v !== undefined) this.currentLevels.set(k as UpgradeCategory, v);
    }
  }
}
